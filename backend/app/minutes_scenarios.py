def profile(scenario: str | None) -> dict:
    return PROFILES.get((scenario or "").strip(), PROFILES["meeting"])


def name(scenario: str | None, language: str | None) -> str:
    return profile(scenario)["name"][label_language(language)]


def tip(scenario: str | None, language: str | None) -> str:
    return profile(scenario)["tip"][label_language(language)]


def labels(scenario: str | None, language: str | None) -> dict:
    return profile(scenario)["labels"][label_language(language)]


def section_order(scenario: str | None) -> tuple[str, ...]:
    return profile(scenario)["sections"]


def topics_cap(duration: float, scenario: str = "meeting") -> int:
    """主题/章节/看点的上限：会议 3 分钟一段、视频和直播 5 分钟一段。"""
    try:
        span = max(0.0, float(duration or 0))
    except (TypeError, ValueError):
        span = 0.0
    if scenario == "video":
        return max(1, min(12, int(span // 300) + 1))
    if scenario == "live":
        return max(1, min(10, int(span // 300) + 1))
    return max(1, min(8, int(span // 180) + 1))
