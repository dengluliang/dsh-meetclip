def label_language(language: str | None) -> str:
    """段落标题用中文还是英文：中文（含简繁）用中文，其余回落到英文。"""
    text = (language or "").strip().lower()
    if not text:
        return "zh"
    if any(word in text for word in ("chinese", "mandarin", "cantonese", "中文")):
        return "zh"
    return "en"


