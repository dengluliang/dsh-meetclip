import { build } from 'esbuild'
import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const here = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(here, '..')
const manifest = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8'))

const result = await build({
  entryPoints: [path.join(root, 'client-src/index.jsx')],
  absWorkingDir: root,
  nodePaths: [path.join(root, 'build', 'node_modules')],
  bundle: true,
  write: false,
  format: 'cjs',
  platform: 'browser',
  target: 'es2020',
  external: ['react'],
  loader: { '.css': 'text' },
  jsxFactory: 'React.createElement',
  jsxFragment: 'React.Fragment',
  inject: [path.join(root, 'client-src/react-shim.js')],
  define: { 'process.env.NODE_ENV': '"production"' },
  minify: false,
  logLevel: 'info'
})

const bundled = result.outputFiles[0].text
const out = [
  '/* Generated by build/build-client.mjs. Do not edit by hand. */',
  'window.__ModuleLoader__.load({',
  `  id: ${JSON.stringify(manifest.name)},`,
  '  factory(require) {',
  '    const module = { exports: {} };',
  '    const exports = module.exports;',
  '(function (module, exports, require) {',
  bundled,
  '})(module, module.exports, require);',
  '    return module.exports;',
  '  },',
  '});',
  ''
].join('\n')

await writeFile(path.join(root, 'client.js'), out)
console.log(`client.js written (${Buffer.byteLength(out)} bytes) for ${manifest.name}`)
